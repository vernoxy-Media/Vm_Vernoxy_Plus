-- Baseline: codify CRM / lead objects that already exist in the live database
-- but were never captured in a migration (schema drift).
--
-- Every statement is idempotent. On the live database this migration is a
-- no-op; on a fresh database it creates the same objects, so both end up with
-- the same schema. Nothing is dropped except ck_leads_status_consistency, which
-- the live database has already lost (it conflicts with the "Converted" flow).
--
-- NOTE: leads.company_name .. leads.on_hold_follow_up_date duplicate company
-- data inside leads. The Lead Management module does NOT use those copies; the
-- company stays the single source of truth (companies / persons tables).
-- =============================================================================

-- 1. leads: columns present in live ------------------------------------------
