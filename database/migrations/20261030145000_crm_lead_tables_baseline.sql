    ADD COLUMN IF NOT EXISTS state varchar(100),
    ADD COLUMN IF NOT EXISTS country varchar(100) DEFAULT 'India',
    ADD COLUMN IF NOT EXISTS pin varchar(20),
    ADD COLUMN IF NOT EXISTS google_maps_url text,
    ADD COLUMN IF NOT EXISTS is_gidc boolean DEFAULT false,
    ADD COLUMN IF NOT EXISTS gidc_name varchar(150),
    ADD COLUMN IF NOT EXISTS gidc_area_phase varchar(150),
    ADD COLUMN IF NOT EXISTS contact_person varchar(150),
    ADD COLUMN IF NOT EXISTS designation varchar(100),
    ADD COLUMN IF NOT EXISTS mobile varchar(25),
    ADD COLUMN IF NOT EXISTS email varchar(255),
    ADD COLUMN IF NOT EXISTS nature_of_business varchar(100),
    ADD COLUMN IF NOT EXISTS industry varchar(100),
    ADD COLUMN IF NOT EXISTS industry_id integer,
    ADD COLUMN IF NOT EXISTS products_services text,
    ADD COLUMN IF NOT EXISTS estimated_employees integer,
    ADD COLUMN IF NOT EXISTS estimated_turnover numeric(15,2),
    ADD COLUMN IF NOT EXISTS year_established integer,
    ADD COLUMN IF NOT EXISTS existing_major_clients text,
    ADD COLUMN IF NOT EXISTS website text,
    ADD COLUMN IF NOT EXISTS website_quality varchar(50),
    ADD COLUMN IF NOT EXISTS developed_by varchar(200),
    ADD COLUMN IF NOT EXISTS linkedin_url text,
    ADD COLUMN IF NOT EXISTS instagram_url text,
    ADD COLUMN IF NOT EXISTS facebook_url text,
    ADD COLUMN IF NOT EXISTS youtube_url text,
    ADD COLUMN IF NOT EXISTS google_business_profile_url text,
    ADD COLUMN IF NOT EXISTS brochure_url text,
    ADD COLUMN IF NOT EXISTS lead_source varchar(100) DEFAULT 'Cold calling',
    ADD COLUMN IF NOT EXISTS lead_by_id integer,
    ADD COLUMN IF NOT EXISTS service_fit varchar(150),
    ADD COLUMN IF NOT EXISTS lead_stage varchar(50) DEFAULT 'New',
    ADD COLUMN IF NOT EXISTS lead_code varchar(50),
    ADD COLUMN IF NOT EXISTS won_on date,
    ADD COLUMN IF NOT EXISTS win_note text,
    ADD COLUMN IF NOT EXISTS lost_reason varchar(150),
    ADD COLUMN IF NOT EXISTS lost_note text,
    ADD COLUMN IF NOT EXISTS on_hold_reason text,
    ADD COLUMN IF NOT EXISTS on_hold_follow_up_date timestamptz;

-- Live allows leads without company / title (legacy). Match live.
ALTER TABLE leads ALTER COLUMN company_id DROP NOT NULL;
ALTER TABLE leads ALTER COLUMN title DROP NOT NULL;

-- Live no longer has this constraint ("won" required actual_value).
ALTER TABLE leads DROP CONSTRAINT IF EXISTS ck_leads_status_consistency;

CREATE UNIQUE INDEX IF NOT EXISTS leads_lead_code_key ON leads (lead_code);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'leads_industry_id_fkey') THEN
        ALTER TABLE leads ADD CONSTRAINT leads_industry_id_fkey
            FOREIGN KEY (industry_id) REFERENCES industries(industry_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'leads_lead_by_id_fkey') THEN
        ALTER TABLE leads ADD CONSTRAINT leads_lead_by_id_fkey
            FOREIGN KEY (lead_by_id) REFERENCES employees(emp_id);
    END IF;
END $$;

-- 2. crm_communications ------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_communications (
    communication_id integer GENERATED BY DEFAULT AS IDENTITY,
    company_id integer,
    lead_id integer,
    contact_id integer,
    contact_person_name varchar(150),
    type varchar(50) NOT NULL,
    communication_date timestamptz NOT NULL DEFAULT now(),
    what_discussed text NOT NULL,
    outcome varchar(100),
    attachment_url text,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz,
    deleted_at timestamptz,
    CONSTRAINT crm_communications_pkey PRIMARY KEY (communication_id),
    CONSTRAINT crm_communications_company_id_fkey FOREIGN KEY (company_id) REFERENCES companies(company_id) ON DELETE CASCADE,
    CONSTRAINT crm_communications_contact_id_fkey FOREIGN KEY (contact_id) REFERENCES persons(person_id) ON DELETE SET NULL,
    CONSTRAINT crm_communications_created_by_fkey FOREIGN KEY (created_by) REFERENCES employees(emp_id) ON DELETE SET NULL,
    CONSTRAINT crm_communications_lead_id_fkey FOREIGN KEY (lead_id) REFERENCES leads(lead_id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_crm_comm_company ON crm_communications (company_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_crm_comm_date ON crm_communications (communication_date DESC);
CREATE INDEX IF NOT EXISTS idx_crm_comm_lead ON crm_communications (lead_id) WHERE deleted_at IS NULL;

-- 3. crm_follow_ups ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_follow_ups (
    follow_up_id integer GENERATED BY DEFAULT AS IDENTITY,
    company_id integer,
    lead_id integer,
    contact_id integer,
    contact_person_name varchar(150),
    follow_up_on timestamptz NOT NULL,
    type varchar(50) NOT NULL,
    assigned_to integer NOT NULL,
    purpose text,
    status varchar(50) NOT NULL DEFAULT 'Pending',
    rescheduled_count integer NOT NULL DEFAULT 0,
    done_on timestamptz,
    outcome varchar(100),
    what_happened text,
    reason text,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz,
    deleted_at timestamptz,
    CONSTRAINT crm_follow_ups_pkey PRIMARY KEY (follow_up_id),
    CONSTRAINT crm_follow_ups_assigned_to_fkey FOREIGN KEY (assigned_to) REFERENCES employees(emp_id),
    CONSTRAINT crm_follow_ups_company_id_fkey FOREIGN KEY (company_id) REFERENCES companies(company_id) ON DELETE CASCADE,
    CONSTRAINT crm_follow_ups_contact_id_fkey FOREIGN KEY (contact_id) REFERENCES persons(person_id) ON DELETE SET NULL,
    CONSTRAINT crm_follow_ups_created_by_fkey FOREIGN KEY (created_by) REFERENCES employees(emp_id) ON DELETE SET NULL,
    CONSTRAINT crm_follow_ups_lead_id_fkey FOREIGN KEY (lead_id) REFERENCES leads(lead_id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_crm_fu_assigned_status ON crm_follow_ups (assigned_to, status) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_crm_fu_date ON crm_follow_ups (follow_up_on);
CREATE INDEX IF NOT EXISTS idx_crm_fu_lead ON crm_follow_ups (lead_id) WHERE deleted_at IS NULL;

-- 4. crm_lead_notes ----------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_lead_notes (
    note_id integer GENERATED BY DEFAULT AS IDENTITY,
    lead_id integer NOT NULL,
    company_id integer,
    note_type varchar(50) NOT NULL DEFAULT 'General',
    note text NOT NULL,
    is_pinned boolean NOT NULL DEFAULT false,
    attachment_url text,
    created_by integer,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz,
    deleted_at timestamptz,
    CONSTRAINT crm_lead_notes_pkey PRIMARY KEY (note_id),
    CONSTRAINT crm_lead_notes_company_id_fkey FOREIGN KEY (company_id) REFERENCES companies(company_id) ON DELETE CASCADE,
    CONSTRAINT crm_lead_notes_created_by_fkey FOREIGN KEY (created_by) REFERENCES employees(emp_id) ON DELETE SET NULL,
    CONSTRAINT crm_lead_notes_lead_id_fkey FOREIGN KEY (lead_id) REFERENCES leads(lead_id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_crm_notes_lead ON crm_lead_notes (lead_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_crm_notes_pinned ON crm_lead_notes (lead_id, is_pinned DESC);

-- 5. crm_import_batches ------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_import_batches (
    batch_id integer GENERATED BY DEFAULT AS IDENTITY,
    file_name varchar(255) NOT NULL,
    imported_by integer NOT NULL,
    imported_at timestamptz NOT NULL DEFAULT now(),
    can_undo_until timestamptz NOT NULL,
    is_undone boolean NOT NULL DEFAULT false,
    companies_created jsonb DEFAULT '[]'::jsonb,
    leads_created jsonb DEFAULT '[]'::jsonb,
    CONSTRAINT crm_import_batches_pkey PRIMARY KEY (batch_id),
    CONSTRAINT crm_import_batches_imported_by_fkey FOREIGN KEY (imported_by) REFERENCES employees(emp_id)
);
CREATE INDEX IF NOT EXISTS idx_crm_import_batches_undo ON crm_import_batches (can_undo_until) WHERE is_undone = false;

