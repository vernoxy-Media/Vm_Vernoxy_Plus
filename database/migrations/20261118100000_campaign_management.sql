-- migrate:up
-- Campaign Management (Calling): an admin creates a campaign, picks companies from the existing Company Database,
-- hands them to employees with a daily call target, and the employees log calls against them.
-- Only NEW tables: no existing table or column is changed. A campaign never copies a company; it points to it.

-- 1. The campaign itself ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_campaigns (
    campaign_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            varchar(200) NOT NULL,
    campaign_type   varchar(30)  NOT NULL DEFAULT 'Calling',
    target_cities   text[]       NOT NULL DEFAULT '{}',
    target_state    varchar(100),
    industry_id     integer REFERENCES industries(industry_id),
    start_date      date         NOT NULL,
    end_date        date         NOT NULL,
    objective       text,
    description     text,
    status          varchar(20)  NOT NULL DEFAULT 'Draft',
    created_at      timestamptz  NOT NULL DEFAULT clock_timestamp(),
    created_by      integer REFERENCES employees(emp_id),
    updated_at      timestamptz,
    updated_by      integer REFERENCES employees(emp_id),
    deleted_at      timestamptz,
    deleted_by      integer REFERENCES employees(emp_id),
    CONSTRAINT ck_crm_campaigns_type    CHECK (campaign_type IN ('Calling', 'Meeting', 'Email', 'Calling + Meeting')),
    CONSTRAINT ck_crm_campaigns_status  CHECK (status IN ('Draft', 'Active', 'Paused', 'Completed')),
    CONSTRAINT ck_crm_campaigns_dates   CHECK (end_date >= start_date),
    CONSTRAINT ck_crm_campaigns_deleted_by CHECK (deleted_by IS NULL OR deleted_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS ix_crm_campaigns_status ON crm_campaigns (status) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_crm_campaigns_dates  ON crm_campaigns (start_date, end_date) WHERE deleted_at IS NULL;

-- 2. Each employee's daily call target in a campaign -----------------------------------------------------
CREATE TABLE IF NOT EXISTS crm_campaign_targets (
    target_id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id   integer     NOT NULL REFERENCES crm_campaigns(campaign_id),
    emp_id        integer     NOT NULL REFERENCES employees(emp_id),
    daily_target  integer     NOT NULL DEFAULT 0,
    created_at    timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by    integer REFERENCES employees(emp_id),
    updated_at    timestamptz,
    updated_by    integer REFERENCES employees(emp_id),
    deleted_at    timestamptz,
    deleted_by    integer REFERENCES employees(emp_id),
    CONSTRAINT ck_crm_campaign_targets_value CHECK (daily_target >= 0 AND daily_target <= 1000),
    CONSTRAINT ck_crm_campaign_targets_deleted_by CHECK (deleted_by IS NULL OR deleted_at IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_crm_campaign_targets_emp
    ON crm_campaign_targets (campaign_id, emp_id) WHERE deleted_at IS NULL;

-- 3. A company inside a campaign, and the employee who owns it there --------------------------------------------
-- The same company may sit in many campaigns; each campaign keeps its own assignment and call progress.
-- assigned_to NULL means "not assigned yet". Progress columns are a summary of crm_campaign_calls.
CREATE TABLE IF NOT EXISTS crm_campaign_companies (
    campaign_company_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id         integer     NOT NULL REFERENCES crm_campaigns(campaign_id),
    company_id          integer     NOT NULL REFERENCES companies(company_id),
    assigned_to         integer REFERENCES employees(emp_id),
    call_attempts       integer     NOT NULL DEFAULT 0,
    last_call_status    varchar(20),
    last_outcome        varchar(100),
    last_called_at      timestamptz,
    next_follow_up_on   timestamptz,
    created_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by          integer REFERENCES employees(emp_id),
    updated_at          timestamptz,
    updated_by          integer REFERENCES employees(emp_id),
    deleted_at          timestamptz,
    deleted_by          integer REFERENCES employees(emp_id),
    CONSTRAINT ck_crm_campaign_companies_attempts CHECK (call_attempts >= 0),
    CONSTRAINT ck_crm_campaign_companies_call_status CHECK (last_call_status IS NULL OR last_call_status IN ('Received', 'Not received')),
    CONSTRAINT ck_crm_campaign_companies_deleted_by CHECK (deleted_by IS NULL OR deleted_at IS NOT NULL)
);
-- One company appears once per campaign, so one employee owns it: no double calling.
CREATE UNIQUE INDEX IF NOT EXISTS ux_crm_campaign_companies_company
    ON crm_campaign_companies (campaign_id, company_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_crm_campaign_companies_assignee
    ON crm_campaign_companies (assigned_to, campaign_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_crm_campaign_companies_company_id
    ON crm_campaign_companies (company_id) WHERE deleted_at IS NULL;

-- 4. Every call attempt made for a campaign company -------------------------------------------------------------
-- The call is also written to crm_communications (the company's normal history); communication_id links the two.
CREATE TABLE IF NOT EXISTS crm_campaign_calls (
    call_id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_company_id integer     NOT NULL REFERENCES crm_campaign_companies(campaign_company_id),
    campaign_id         integer     NOT NULL REFERENCES crm_campaigns(campaign_id),
    company_id          integer     NOT NULL REFERENCES companies(company_id),
    emp_id              integer     NOT NULL REFERENCES employees(emp_id),
    communication_id    integer REFERENCES crm_communications(communication_id),
    call_status         varchar(20) NOT NULL,
    outcome             varchar(100),
    called_at           timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_at          timestamptz NOT NULL DEFAULT clock_timestamp(),
    created_by          integer REFERENCES employees(emp_id),
    updated_at          timestamptz,
    updated_by          integer REFERENCES employees(emp_id),
    deleted_at          timestamptz,
    deleted_by          integer REFERENCES employees(emp_id),
    CONSTRAINT ck_crm_campaign_calls_status CHECK (call_status IN ('Received', 'Not received')),
    CONSTRAINT ck_crm_campaign_calls_deleted_by CHECK (deleted_by IS NULL OR deleted_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS ix_crm_campaign_calls_campaign ON crm_campaign_calls (campaign_id, called_at) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_crm_campaign_calls_emp_day  ON crm_campaign_calls (emp_id, called_at)      WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_crm_campaign_calls_company  ON crm_campaign_calls (campaign_company_id)     WHERE deleted_at IS NULL;

-- Same rules as every other table: rows are soft-deleted, never removed; created_* never change.
DO $$
DECLARE
    tbl text;
BEGIN
    FOREACH tbl IN ARRAY ARRAY['crm_campaigns', 'crm_campaign_targets', 'crm_campaign_companies', 'crm_campaign_calls'] LOOP
        EXECUTE format('CREATE TRIGGER %I BEFORE DELETE ON %I FOR EACH ROW EXECUTE FUNCTION fn_prevent_hard_delete()', 'trg_prevent_hard_delete_' || tbl, tbl);
        EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION fn_handle_update_audit()', 'trg_handle_update_audit_' || tbl, tbl);
    END LOOP;
END $$;

-- migrate:down
DROP TABLE IF EXISTS crm_campaign_calls;
DROP TABLE IF EXISTS crm_campaign_companies;
DROP TABLE IF EXISTS crm_campaign_targets;
DROP TABLE IF EXISTS crm_campaigns;
