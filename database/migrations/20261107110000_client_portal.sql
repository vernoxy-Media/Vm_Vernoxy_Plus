-- Client portal: a client signs in with its own login (separate from employees) and sees its own projects.

-- 1. A project belongs to a client (the CRM client it is built for).
ALTER TABLE projects ADD COLUMN IF NOT EXISTS client_id integer REFERENCES clients(client_id);
CREATE INDEX IF NOT EXISTS ix_projects_client_id ON projects(client_id) WHERE deleted_at IS NULL;

-- Projects that already carry a client name are linked to the one client that has that company name.
UPDATE projects p
   SET client_id = m.client_id
  FROM (
        SELECT lower(co.name) AS name_key, min(c.client_id) AS client_id
          FROM clients c
          JOIN companies co ON co.company_id = c.company_id
         WHERE c.deleted_at IS NULL AND co.deleted_at IS NULL
         GROUP BY lower(co.name)
        HAVING count(*) = 1
       ) m
 WHERE p.client_id IS NULL
   AND p.client_name IS NOT NULL
   AND lower(btrim(p.client_name)) = m.name_key;

-- 2. The logins. The password is only ever stored as a hash; nobody (not even an admin) can read it back.
CREATE TABLE IF NOT EXISTS client_users (
    client_user_id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id            integer      NOT NULL REFERENCES clients(client_id),
    name                 varchar(150) NOT NULL,
    email                varchar(255) NOT NULL,
    password_hash        varchar(255) NOT NULL,
    must_change_password boolean      NOT NULL DEFAULT true,
    is_active            boolean      NOT NULL DEFAULT true,
    failed_attempts      smallint     NOT NULL DEFAULT 0,
    locked_until         timestamptz,
    last_login_at        timestamptz,
    reset_code_hash      char(64),
    reset_expires_at     timestamptz,
    reset_attempts       smallint     NOT NULL DEFAULT 0,
    created_at           timestamptz  NOT NULL DEFAULT clock_timestamp(),
    created_by           integer REFERENCES employees(emp_id),
    updated_at           timestamptz,
    updated_by           integer REFERENCES employees(emp_id),
    deleted_at           timestamptz,
    deleted_by           integer REFERENCES employees(emp_id),
    CONSTRAINT ck_client_users_deleted_by CHECK (deleted_by IS NULL OR deleted_at IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_client_users_email ON client_users (lower(email)) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_client_users_client_id ON client_users (client_id) WHERE deleted_at IS NULL;

-- Same rule as every other table: rows are soft-deleted, never deleted for real.
CREATE TRIGGER trg_prevent_hard_delete_client_users
    BEFORE DELETE ON client_users
    FOR EACH ROW EXECUTE FUNCTION fn_prevent_hard_delete();

